const lang = new URLSearchParams(location.search).get('lang') || 'en',
  m = translations[lang] || translations.en;
document.documentElement.lang = translations[lang] ? lang : 'en';
document.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = m[el.dataset.i18n]));
document.querySelectorAll('nav a').forEach((a) => {
  if (a.textContent.toLowerCase() === document.documentElement.lang)
    a.setAttribute('aria-current', 'page');
});
const $ = (id) => document.getElementById(id),
  el = (tag, text, cls) => {
    const x = document.createElement(tag);
    if (text !== undefined) x.textContent = text;
    if (cls) x.className = cls;
    return x;
  };
for (const option of $('outcome').options) option.textContent = m[option.value];
let state,
  report,
  initial,
  serial = 0;
function render(data) {
  state = data.case;
  report = data.report;
  $('entropy').textContent = report.entropy_bits.toFixed(3);
  $('budget').textContent = state.remaining_budget.toFixed(1);
  $('count').textContent = state.observations.length;
  $('recommendation').textContent = report.recommendation || m.none;
  $('digest').textContent = report.input_sha256;
  $('simulate').disabled = !report.recommendation;
  $('record').disabled = !report.recommendation;
  $('posterior').replaceChildren();
  $('candidates').replaceChildren();
  $('history').replaceChildren();
  for (const hypothesis of report.posterior) {
    const row = el('div', undefined, 'hypothesis');
    row.append(
      el('span', hypothesis.id),
      el('strong', `${(100 * hypothesis.probability).toFixed(1)}%`),
    );
    const track = el('div', undefined, 'belief-track'),
      bar = el('div', undefined, 'belief-bar');
    bar.style.width = `${100 * hypothesis.probability}%`;
    track.append(bar);
    row.append(track);
    $('posterior').append(row);
  }
  for (const candidate of report.candidates) {
    const row = el('tr');
    if (candidate.id === report.recommendation) row.className = 'recommended';
    row.append(
      el('td', candidate.id),
      el('td', candidate.information_per_cost.toFixed(3)),
      el('td', `${(100 * candidate.prediction.damaged).toFixed(1)}%`),
      el('td', candidate.eligible ? m.eligible : candidate.exclusions.map((x) => m[x]).join(' · ')),
    );
    $('candidates').append(row);
  }
  for (const observation of state.observations) {
    const row = el('div', undefined, 'observation');
    const synthetic = observation.evidence_id?.startsWith('simulation:');
    row.append(
      el('span', observation.design),
      el('span', m[observation.outcome]),
      el('small', synthetic ? m.simulation : m.measurement),
    );
    $('history').append(row);
  }
  if (!state.observations.length) $('history').append(el('p', m.empty, 'hint'));
  $('status').textContent = m.ready;
}
async function request(path, extra = {}) {
  $('status').textContent = m.busy;
  $('simulate').disabled = true;
  $('record').disabled = true;
  try {
    const response = await fetch(path, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ case: state, ...extra }),
    });
    if (!response.ok) throw Error();
    render(await response.json());
  } catch {
    $('status').textContent = m.error;
    $('simulate').disabled = !report?.recommendation;
    $('record').disabled = !report?.recommendation;
  }
}
$('risk').addEventListener('input', () => {
  $('risk-value').value = $('risk').value + '%';
});
$('risk').addEventListener('change', () => {
  state.max_damage_probability = Number($('risk').value) / 100;
  request('/api/analyze');
});
$('simulate').addEventListener('click', () =>
  request('/api/simulate', { true_hypothesis: $('truth').value, seed: 7 }),
);
$('record').addEventListener('click', () =>
  request('/api/observe', {
    design: report.recommendation,
    outcome: $('outcome').value,
    evidence_id: `entered:${Date.now()}:${serial++}`,
  }),
);
$('reset').addEventListener('click', () => {
  render(structuredClone(initial));
  $('risk').value = 25;
  $('risk-value').value = '25%';
});
$('download').addEventListener('click', () => {
  if (!state) return;
  const url = URL.createObjectURL(
    new Blob([JSON.stringify({ case: state, report }, null, 2)], { type: 'application/json' }),
  );
  const a = el('a');
  a.href = url;
  a.download = 'fab-discovery-evidence.json';
  a.click();
  URL.revokeObjectURL(url);
});
